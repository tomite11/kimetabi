CREATE TABLE expense (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trip(id),
    plan_item_id BIGINT,
    created_by_member_id BIGINT NOT NULL,
    payer_id BIGINT,
    amount BIGINT,
    currency CHAR(3),
    base_amount BIGINT,
    paid_at TIMESTAMPTZ,
    source VARCHAR(10) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'DRAFT',
    allocation_type VARCHAR(20),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    CONSTRAINT uq_expense_id_trip UNIQUE (id, trip_id),
    CONSTRAINT fk_expense_plan_item
        FOREIGN KEY (plan_item_id, trip_id)
        REFERENCES plan_item(id, trip_id),
    CONSTRAINT fk_expense_creator
        FOREIGN KEY (created_by_member_id, trip_id)
        REFERENCES trip_member(id, trip_id),
    CONSTRAINT fk_expense_payer
        FOREIGN KEY (payer_id, trip_id)
        REFERENCES trip_member(id, trip_id),
    CONSTRAINT ck_expense_source CHECK (source IN ('PLAN', 'MANUAL')),
    CONSTRAINT ck_expense_status CHECK (status IN ('DRAFT', 'CONFIRMED')),
    CONSTRAINT ck_expense_mvp_currency
        CHECK (currency IS NULL OR currency = 'JPY'),
    CONSTRAINT ck_expense_confirmed
        CHECK (
            (status = 'DRAFT' AND confirmed_at IS NULL)
            OR (
                status = 'CONFIRMED'
                AND payer_id IS NOT NULL
                AND amount IS NOT NULL
                AND amount > 0
                AND currency = 'JPY'
                AND base_amount IS NOT NULL
                AND base_amount = amount
                AND paid_at IS NOT NULL
                AND allocation_type IN ('EQUAL', 'WEIGHT', 'FIXED_AND_WEIGHT')
                AND confirmed_at IS NOT NULL
            )
        )
);

CREATE INDEX ix_expense_trip_page
