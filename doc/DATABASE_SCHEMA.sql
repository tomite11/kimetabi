    image_url TEXT,
    note VARCHAR(2000),
    est_amount BIGINT,
    est_basis VARCHAR(10),
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    metadata_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    metadata_error_code VARCHAR(50),
    metadata_attempts INTEGER NOT NULL DEFAULT 0,
    metadata_updated_at TIMESTAMPTZ,
    metadata_request_event_id UUID,
    title_edited_at TIMESTAMPTZ,
    image_edited_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_candidate_id_trip UNIQUE (id, trip_id),
    CONSTRAINT fk_candidate_slot
        FOREIGN KEY (slot_id, trip_id) REFERENCES slot(id, trip_id),
    CONSTRAINT fk_candidate_creator
        FOREIGN KEY (created_by_member_id, trip_id)
        REFERENCES trip_member(id, trip_id),
    CONSTRAINT ck_candidate_source CHECK (title IS NOT NULL OR url IS NOT NULL),
    CONSTRAINT ck_candidate_estimate CHECK (est_amount IS NULL OR est_amount >= 0),
    CONSTRAINT ck_candidate_estimate_pair
        CHECK (
            (est_amount IS NULL AND est_basis IS NULL)
            OR (
                est_amount IS NOT NULL
                AND est_basis IN ('PER_PERSON', 'TOTAL')
