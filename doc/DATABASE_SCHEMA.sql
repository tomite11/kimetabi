CREATE TABLE settlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trip(id),
    created_by_member_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    superseded_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_settlement_id_trip UNIQUE (id, trip_id),
    CONSTRAINT fk_settlement_creator
        FOREIGN KEY (created_by_member_id, trip_id)
        REFERENCES trip_member(id, trip_id),
    CONSTRAINT ck_settlement_status
        CHECK (status IN ('DRAFT', 'CONFIRMED', 'COMPLETED', 'SUPERSEDED')),
    CONSTRAINT ck_settlement_status_time
        CHECK (
            (
                status = 'DRAFT'
                AND confirmed_at IS NULL
                AND completed_at IS NULL
                AND superseded_at IS NULL
            )
            OR (
                status = 'CONFIRMED'
                AND confirmed_at IS NOT NULL
                AND completed_at IS NULL
                AND superseded_at IS NULL
            )
            OR (
                status = 'COMPLETED'
                AND confirmed_at IS NOT NULL
                AND completed_at IS NOT NULL
                AND superseded_at IS NULL
            )
            OR (
                status = 'SUPERSEDED'
                AND completed_at IS NULL
                AND superseded_at IS NOT NULL
            )
        )
);

CREATE INDEX ix_settlement_trip_created
    ON settlement(trip_id, created_at DESC);

